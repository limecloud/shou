using System.Diagnostics;
using System.Security.Principal;
using Shou.Windows.Core;
using static Shou.Windows.Platform.Tests.WindowsFileSystemTests;

namespace Shou.Windows.Platform.Tests;

public sealed class WindowsArtifactTrackingTests
{
    private static string Owner => WindowsIdentity.GetCurrent().User!.Value;

    private sealed class GitFixture : IDisposable
    {
        internal NativeFixture Files { get; } = new();
        public void Dispose()
        {
            // Git marks its generated loose objects read-only. Normalize only this fixture's object files at teardown.
            var objects = Path.Combine(Files.Root, ".git", "objects");
            if (Directory.Exists(objects))
                foreach (var file in new DirectoryInfo(objects).EnumerateFiles("*", new EnumerationOptions
                { RecurseSubdirectories = true, AttributesToSkip = FileAttributes.ReparsePoint }))
                    if ((file.Attributes & FileAttributes.ReadOnly) != 0) file.Attributes &= ~FileAttributes.ReadOnly;
            Files.Dispose();
        }
    }

    private static async Task Git(NativeFixture fixture, params string[] arguments)
    {
        var start = new ProcessStartInfo("git") { WorkingDirectory = fixture.Root, UseShellExecute = false,
            RedirectStandardInput = true, RedirectStandardOutput = true, RedirectStandardError = true, CreateNoWindow = true };
        foreach (var key in start.Environment.Keys.Where(key => key.StartsWith("GIT_", StringComparison.OrdinalIgnoreCase)).ToArray()) start.Environment.Remove(key);
        start.Environment["GIT_CONFIG_NOSYSTEM"] = "1";
        start.Environment["GIT_CONFIG_GLOBAL"] = "NUL";
        start.Environment["GIT_TERMINAL_PROMPT"] = "0";
        start.ArgumentList.Add("-c"); start.ArgumentList.Add("index.version=2");
        foreach (var argument in arguments) start.ArgumentList.Add(argument);
        using var process = Process.Start(start) ?? throw new InvalidOperationException("Generated Git fixture failed to start.");
        process.StandardInput.Close();
        var output = process.StandardOutput.ReadToEndAsync(); var error = process.StandardError.ReadToEndAsync();
        using var deadline = new CancellationTokenSource(TimeSpan.FromSeconds(10));
        try { await process.WaitForExitAsync(deadline.Token); }
        catch { if (!process.HasExited) process.Kill(); throw; }
        Assert.True(process.ExitCode == 0, await output + await error);
        if (File.Exists(Path.Combine(fixture.Root, ".git/index"))) fixture.SetFileOwner(".git/index");
    }

    private static async Task Init(NativeFixture fixture)
    {
        fixture.CreateDirectory(".git");
        var empty = fixture.CreateDirectory("empty-template");
        await Git(fixture, "init", "--template=" + empty);
        fixture.Write("source.rs", "fn main() {}"u8.ToArray());
        await Git(fixture, "add", "--", "source.rs");
    }

    [WindowsFact]
    public async Task ActualGitIndexTracksUnicodePathsWithoutChangingMetadataOrSourceBytes()
    {
        using var repository = new GitFixture(); var fixture = repository.Files; await Init(fixture);
        var payload = fixture.Write("项目/target/debug/build/crate-01234567/out/生成.rs", [1, 2, 3]);
        var target = WindowsPath.Parse(Path.Combine(fixture.Root, "项目/target"));
        var service = new WindowsArtifactTracking();
        Assert.False(await service.HasTrackedContentAsync(target, Owner, default));
        await Git(fixture, "add", "--", "项目/target");
        var index = File.ReadAllBytes(Path.Combine(fixture.Root, ".git/index"));
        Assert.True(await service.HasTrackedContentAsync(target, Owner, default));
        Assert.True(await service.HasTrackedContentAsync(WindowsPath.Parse(Path.Combine(fixture.Root, "项目/TARGET")), Owner, default));
        Assert.Equal(index, File.ReadAllBytes(Path.Combine(fixture.Root, ".git/index")));
        Assert.Equal(new byte[] { 1, 2, 3 }, File.ReadAllBytes(payload));
    }

    [WindowsFact]
    public async Task MissingWorktreeCorruptAndLockedIndexesCannotProveAnUntrackedTarget()
    {
        using var fixture = new NativeFixture();
        fixture.CreateDirectory("target");
        var target = WindowsPath.Parse(Path.Combine(fixture.Root, "target"));
        var service = new WindowsArtifactTracking();
        Assert.False(await service.HasTrackedContentAsync(target, Owner, default));
        fixture.Write(".git", "gitdir: C:/unrelated"u8.ToArray());
        await Assert.ThrowsAsync<ShouException>(() => service.HasTrackedContentAsync(target, Owner, default));
        File.Delete(Path.Combine(fixture.Root, ".git")); // Only the marker generated by this test.
        fixture.CreateDirectory(".git");
        await Assert.ThrowsAsync<ShouException>(() => service.HasTrackedContentAsync(target, Owner, default));
        fixture.Write(".git/index", [1, 2, 3]);
        await Assert.ThrowsAsync<ShouException>(() => service.HasTrackedContentAsync(target, Owner, default));
        fixture.Write(".git/index", GitIndexReaderTests.Index([]));
        using var locked = new FileStream(Path.Combine(fixture.Root, ".git/index"), FileMode.Open, FileAccess.Write, FileShare.Read);
        await Assert.ThrowsAsync<ShouException>(() => service.HasTrackedContentAsync(target, Owner, default));
    }

    [WindowsFact]
    public async Task JunctionAndHardLinkedTrackingMetadataRemainUnavailableAndPreserveOutsideBytes()
    {
        using var fixture = new NativeFixture(); using var outside = new NativeFixture();
        fixture.CreateDirectory("target");
        var original = outside.Write("index", GitIndexReaderTests.Index([]));
        var marker = Path.Combine(fixture.Root, ".git");
        var target = WindowsPath.Parse(Path.Combine(fixture.Root, "target"));
        var service = new WindowsArtifactTracking();
        FixtureNative.CreateJunction(marker, outside.Root);
        try { await Assert.ThrowsAsync<ShouException>(() => service.HasTrackedContentAsync(target, Owner, default)); }
        finally { Directory.Delete(marker); }
        fixture.CreateDirectory(".git");
        Assert.True(FixtureNative.CreateHardLink(Path.Combine(marker, "index"), original, 0));
        await Assert.ThrowsAsync<ShouException>(() => service.HasTrackedContentAsync(target, Owner, default));
        Assert.Equal(GitIndexReaderTests.Index([]), File.ReadAllBytes(original));
    }

    [WindowsFact]
    public async Task NestedRepositoriesDoNotHideOuterTrackedContent()
    {
        using var repository = new GitFixture(); var fixture = repository.Files; await Init(fixture);
        fixture.Write("nested/target/cache.bin", [1, 2, 3]);
        await Git(fixture, "add", "--", "nested/target");
        fixture.Write("nested/.git/index", GitIndexReaderTests.Index([]));
        Assert.True(await new WindowsArtifactTracking().HasTrackedContentAsync(WindowsPath.Parse(Path.Combine(fixture.Root, "nested/target")), Owner, default));
    }
}
