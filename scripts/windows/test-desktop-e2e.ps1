        $Rule = Get-Content -LiteralPath (Join-Path $Source 'examples/rules/rust-target.rule.json') -Raw | ConvertFrom-Json
        $Rule.platforms = @('windows')
        $Rule.conditions = @{ min_allocated_bytes = 0 }
        $RuleFile = Join-Path $ShouRun 'generated.rule.json'
        Write-Fixture $RuleFile ([Text.Encoding]::UTF8.GetBytes(($Rule | ConvertTo-Json -Depth 20)))
        $null = Run-Cli 'rule-import' @('rules', 'import', '--file', $RuleFile)
        $null = Run-Cli 'rule-enable' @('rules', 'enable', '--rule-id', $Rule.id, '--workspace', $Workspace)
        $Scan = (Run-Cli 'fixture-scan' @('scan', '--workspace', $Workspace)).data
        Assert-That ($Scan.candidate_count -gt 0 -and -not $Scan.preview_only) 'Generated scan has no production candidates.'
        $Candidates = (Run-Cli 'fixture-results' @('scan', 'results', '--scan-id', $Scan.scan_id)).data.candidates
        $Candidate = @($Candidates | Where-Object { $_.rule_id -eq $Rule.id })
        Assert-That ($Candidate.Count -eq 1) 'Generated personal rule did not match exactly one target.'
        $Plan = (Run-Cli 'fixture-plan' @('plan', 'create', '--scan-id', $Scan.scan_id, '--candidate', $Candidate[0].id, '--mode', 'permanent')).data
        Assert-That ($Plan.items.Count -eq 1 -and $Plan.action -eq 'permanent') 'Plan differs from the selected generated target.'
        $Capabilities = (Run-Cli 'mutation-capabilities' @('capabilities')).data
        Assert-That ($Capabilities.mutation_available -ne [bool]$ReadOnlyPreview) 'Select ReadOnlyPreview only for a payload with closed public mutation gates.'
        if ($Capabilities.mutation_available) {
            $Rejected = Run-Cli 'mutation-no-tty' @('plan', 'execute', '--plan-id', $Plan.id) @(7) 'confirmation_required'
            Assert-That ($Rejected.error.code -eq 'confirmation_required') 'Noninteractive cleanup must require current confirmation.'
        } else {
            $Rejected = Run-Cli 'mutation-gate-closed' @('plan', 'execute', '--plan-id', $Plan.id) @(8) 'unsupported_capability'
            Assert-That ($Rejected.error.code -eq 'unsupported_capability') 'Public cleanup must remain unavailable until native acceptance.'
        }
        Assert-That (Test-Path -LiteralPath (Join-Path $ShouPayload 'target')) 'Unconfirmed cleanup changed the fixture.'
    }
    Run-Step '03-ui-generated-smart-results-and-filter' {
        Start-App
        Invoke-Control 'smart.start'
        $null = Wait-Page 'cleanup' @('ready', 'partial') $ScanTimeoutSeconds
        Assert-That (-not (Find-Control 'cleanup.candidates').Current.IsOffscreen) 'Smart scan did not show results.'
        Set-Text 'cleanup.search' $ShouPayload
        $Groups = @(Wait-Until {
            $Found = (Find-Control 'cleanup.candidates').FindAll([Windows.Automation.TreeScope]::Descendants,
                [Windows.Automation.PropertyCondition]::new([Windows.Automation.AutomationElement]::IsExpandCollapsePatternAvailableProperty, $true))
            if ($Found.Count -gt 0) { $Found }
        } 'filtered cleanup result groups')
        Assert-That ($Groups.Count -gt 0) 'No cleanup result groups are accessible.'
        foreach ($Group in $Groups) { $Group.GetCurrentPattern([Windows.Automation.ExpandCollapsePattern]::Pattern).Expand() }
