function New-PrivateDirectory([string]$Path) {
    $Security = [Security.AccessControl.DirectorySecurity]::new()
    $Security.SetOwner($ShouSid)
    $Security.SetAccessRuleProtection($true, $false)
    foreach ($Principal in @($ShouSid, [Security.Principal.SecurityIdentifier]::new('S-1-5-18'))) {
        $Security.AddAccessRule([Security.AccessControl.FileSystemAccessRule]::new($Principal, 'FullControl', 'ContainerInherit,ObjectInherit', 'None', 'Allow'))
    }
    # Only directories generated by this run are created or assigned permissions.
    $Directory = [IO.DirectoryInfo]::new($Path)
    if ($Directory.Exists) { throw 'E2E refuses an existing fixture directory.' }
    $Directory.Create($Security)
}
function Write-Fixture([string]$Path, [byte[]]$Bytes) {
    [IO.File]::WriteAllBytes($Path, $Bytes)
    $Info = [IO.FileInfo]::new($Path)
    $Security = $Info.GetAccessControl()
    $Security.SetOwner($ShouSid)
    $Info.SetAccessControl($Security)
}
function Assert-That([bool]$Condition, [string]$Message) { if (-not $Condition) { throw $Message } }
function Wait-Until([scriptblock]$Check, [string]$Description, [int]$Seconds = 30) {
    $Deadline = [DateTime]::UtcNow.AddSeconds($Seconds)
    do {
        if ($null -ne $ShouProcess) {
            $ShouProcess.Refresh()
            if ($ShouProcess.HasExited) { throw "App exited while waiting for $Description, exit=$($ShouProcess.ExitCode)." }
        }
        $Value = & $Check
        if ($Value) { return $Value }
        Start-Sleep -Milliseconds 150
    } while ([DateTime]::UtcNow -lt $Deadline)
    throw "Timed out waiting for $Description."
}
function Find-Control([string]$Id, [bool]$Optional = $false) {
    $Condition = [Windows.Automation.PropertyCondition]::new([Windows.Automation.AutomationElement]::AutomationIdProperty, $Id)
    $Result = $ShouWindow.FindFirst([Windows.Automation.TreeScope]::Descendants, $Condition)
    if ($null -eq $Result -and -not $Optional) { throw "Missing UI Automation control: $Id" }
    return $Result
}
function Invoke-Control([string]$Id) {
    $Control = Wait-Until { $Found = Find-Control $Id $true; if ($null -ne $Found -and $Found.Current.IsEnabled -and -not $Found.Current.IsOffscreen) { $Found } } $Id
    $Pattern = $Control.GetCurrentPattern([Windows.Automation.InvokePattern]::Pattern)
    $Pattern.Invoke()
}
function Set-Text([string]$Id, [string]$Value) {
    $Control = Find-Control $Id
    $Pattern = $Control.GetCurrentPattern([Windows.Automation.ValuePattern]::Pattern)
    $Pattern.SetValue($Value)
}
function Find-GeneratedCleanupTarget {
    $Group = Find-Control 'dev.rust-target' $true
    if ($null -eq $Group) { return $null }
    return $Group.FindFirst([Windows.Automation.TreeScope]::Descendants,
        [Windows.Automation.AndCondition]::new(
            [Windows.Automation.PropertyCondition]::new([Windows.Automation.AutomationElement]::NameProperty, (Join-Path $ShouPayload 'target')),
            [Windows.Automation.PropertyCondition]::new([Windows.Automation.AutomationElement]::ControlTypeProperty, [Windows.Automation.ControlType]::CheckBox)))
}
function Wait-Page([string]$Page, [string[]]$States = @('ready', 'partial'), [int]$Seconds = 30) {
    Wait-Until {
        $Control = Find-Control "page.$Page" $true
        if ($null -eq $Control) { return $false }
        $Status = $Control.Current.ItemStatus
        if ($Status -like 'failed*') { throw "Page $Page failed: $Status" }
        if ($States -contains $Status) { return $Status }
    } "page $Page to reach $($States -join '/')" $Seconds
}
function Navigate-Page([string]$Page, [string[]]$States = @('ready', 'partial', 'empty')) {
    if ($Page -eq 'configuration') {
        Invoke-Control 'nav.cleanup'
        $Options = Wait-Until {
            $ShouWindow.FindAll([Windows.Automation.TreeScope]::Descendants,
                [Windows.Automation.PropertyCondition]::new([Windows.Automation.AutomationElement]::NameProperty, 'Cleanup Options')) |
                Where-Object { $_.Current.IsEnabled -and -not $_.Current.IsOffscreen } | Select-Object -First 1
        } 'cleanup options menu'
        $Options.GetCurrentPattern([Windows.Automation.InvokePattern]::Pattern).Invoke()
        $Rules = Wait-Until {
            [Windows.Automation.AutomationElement]::RootElement.FindAll([Windows.Automation.TreeScope]::Descendants,
                [Windows.Automation.AndCondition]::new(
                    [Windows.Automation.PropertyCondition]::new([Windows.Automation.AutomationElement]::ProcessIdProperty, $ShouProcess.Id),
                    [Windows.Automation.PropertyCondition]::new([Windows.Automation.AutomationElement]::NameProperty, 'Cleanup Rules'))) |
                Where-Object { $_.Current.ControlType -eq [Windows.Automation.ControlType]::MenuItem -and -not $_.Current.IsOffscreen } | Select-Object -First 1
        } 'cleanup rules menu item'
        $Rules.GetCurrentPattern([Windows.Automation.InvokePattern]::Pattern).Invoke()
        $null = Wait-Page $Page $States
        return
    }
    $Group = switch ($Page) {
        'privacy' { 'cleanup' }
        'startup' { 'applications' }
        'projects' { 'cleanup' }
        'large' { 'storage' }
        default { $null }
    }
    if ($Group) { Invoke-Control "nav.$Group" }
    Invoke-Control "nav.$Page"
    $null = Wait-Page $Page $States
    Assert-That ([string]::IsNullOrEmpty((Find-Control 'window.status').Current.Name)) 'Window reports a page load failure.'
}
function Assert-CatalogChrome([string]$Page) {
    $State = (Find-Control "page.$Page").Current.ItemStatus
    $Status = Find-Control "$Page.status" $true
    Assert-That ($null -eq $Status -or $Status.Current.IsOffscreen) "Idle $Page repeats a status row outside its summary."
    $Coverage = Find-Control "$Page.coverage" $true
    $VisibleCoverage = $null -ne $Coverage -and -not $Coverage.Current.IsOffscreen
    Assert-That ($VisibleCoverage -eq ($State -eq 'partial')) "$Page coverage summary does not match observed source coverage."
}
function Start-App([bool]$ExpectFailure = $false) {
    $script:ShouProcess = Start-Process -FilePath $ShouApp -PassThru
    $null = Wait-Until {
        $ShouProcess.Refresh()
        if ($ShouProcess.MainWindowHandle -ne [IntPtr]::Zero) { $ShouProcess.MainWindowHandle }
    } 'WinUI main window'
    $script:ShouWindow = [Windows.Automation.AutomationElement]::FromHandle($ShouProcess.MainWindowHandle)
    if ($ExpectFailure) {
        $null = Wait-Until { $Page = Find-Control 'page.cleanup' $true; $null -ne $Page -and $Page.Current.ItemStatus -like 'failed*' } 'expected fixture storage failure'
    } else { $null = Wait-Page 'cleanup' @('empty') }
}
function Close-App {
    if ($null -eq $ShouProcess) { return }
    $ShouProcess.Refresh()
    Assert-That (-not $ShouProcess.HasExited) 'App exited before normal close.'
    Assert-That ($ShouProcess.CloseMainWindow()) 'CloseMainWindow was rejected.'
    Assert-That ($ShouProcess.WaitForExit(10000)) 'App did not close within its budget.'
    Assert-That ($ShouProcess.ExitCode -eq 0) 'App did not close normally.'
    $ShouProcess.Dispose()
    $script:ShouProcess = $null
    $script:ShouWindow = $null
}
function Save-Screenshot([string]$Name) {
    if ($null -eq $ShouWindow) { return }
    $Bounds = $ShouWindow.Current.BoundingRectangle
    if ($Bounds.Width -le 0 -or $Bounds.Height -le 0) { throw 'No visible window bounds for screenshot.' }
    $Bitmap = [Drawing.Bitmap]::new([int]$Bounds.Width, [int]$Bounds.Height)
    $Graphics = [Drawing.Graphics]::FromImage($Bitmap)
    try {
        $Graphics.CopyFromScreen([int]$Bounds.X, [int]$Bounds.Y, 0, 0, $Bitmap.Size)
        $Bitmap.Save((Join-Path $ShouRun "$Name.png"), [Drawing.Imaging.ImageFormat]::Png)
    } finally { $Graphics.Dispose(); $Bitmap.Dispose() }
}
function Save-Checkpoint([string]$ActiveStep, [string]$Outcome) {
    $Path = Join-Path $ShouRun 'checkpoint.json'
    $Temporary = Join-Path $ShouRun 'checkpoint.next.json'
    $Receipt = [ordered]@{
        schema_version = 1; started_utc = $ShouStartedUtc; updated_utc = [DateTime]::UtcNow.ToString('o');
        active_step = $ActiveStep; outcome = $Outcome; steps = @($ShouResults.ToArray());
        verification_complete = $false
    } | ConvertTo-Json -Depth 8
    [IO.File]::WriteAllText($Temporary, $Receipt, [Text.UTF8Encoding]::new($false))
    if (Test-Path -LiteralPath $Path) { [IO.File]::Replace($Temporary, $Path, [NullString]::Value) }
    else { [IO.File]::Move($Temporary, $Path) }
}
function Run-Step([string]$Name, [scriptblock]$Action) {
    $Started = [DateTime]::UtcNow
    Save-Checkpoint $Name 'running'
    try {
        & $Action
        Save-Screenshot $Name
        $Observed = @()
        if ($null -ne $ShouWindow) {
            $Observed = @($ShouWindow.FindAll([Windows.Automation.TreeScope]::Descendants, [Windows.Automation.Condition]::TrueCondition) |
                Where-Object { $_.Current.AutomationId -like 'page.*' } |
                ForEach-Object { [ordered]@{ page = $_.Current.AutomationId; state = $_.Current.ItemStatus } })
        }
        $ShouResults.Add([ordered]@{ name = $Name; outcome = 'passed'; seconds = ([DateTime]::UtcNow - $Started).TotalSeconds; observations = $Observed })
        Save-Checkpoint $Name 'running'
    } catch {
        $ShouResults.Add([ordered]@{ name = $Name; outcome = 'failed'; seconds = ([DateTime]::UtcNow - $Started).TotalSeconds; error = $_.Exception.Message })
        Save-Checkpoint $Name 'failed'
        throw
    }
}
function Test-ExpectedCliRejection([object]$Event, [object[]]$ExpectedRejections) {
    if ($Event.event -ne 'failed' -or $Event.operation -ne 'application.exception') { return $false }
    foreach ($Expected in $ExpectedRejections) {
        if ($Event.parent_id -eq $Expected.operation_id -and $Event.code -eq $Expected.code) { return $true }
    }
    return $false
}
function Run-Cli([string]$Name, [string[]]$Arguments, [int[]]$ExpectedExit = @(0), [string]$ExpectedErrorCode) {
    $Out = Join-Path $ShouRun "$Name.stdout.json"
    $Err = Join-Path $ShouRun "$Name.stderr.txt"
    # All arguments below are generated fixture values; no shell or caller-supplied command is evaluated.
    $Raw = & $ShouCli @Arguments --json 2> $Err
    $Exit = $LASTEXITCODE
    [IO.File]::WriteAllText($Out, ($Raw -join "`n"))
    Assert-That ($ExpectedExit -contains $Exit) "CLI $Name exited $Exit. See $Out."
    $Json = ($Raw -join "`n") | ConvertFrom-Json
    Assert-That ($Json.api_version -eq '1.0') "CLI $Name returned an invalid envelope."
    if ($ExpectedErrorCode) {
        Assert-That ($Exit -ne 0 -and $Json.error.code -eq $ExpectedErrorCode) "CLI $Name did not reject with $ExpectedErrorCode."
        Assert-That ($Json.request_id -cmatch '^request_[0-9a-f]{32}$') "CLI $Name returned an invalid diagnostic request ID."
        $Expected = [ordered]@{ command = $Name; operation_id = $Json.request_id.Substring(8); code = $ExpectedErrorCode }
        $Events = @(Get-ChildItem -LiteralPath $env:SHOU_DIAGNOSTICS_DIR -Filter 'application.jsonl*' |
            ForEach-Object { Get-Content -LiteralPath $_.FullName } | ForEach-Object { $_ | ConvertFrom-Json })
        $Matching = @($Events | Where-Object { Test-ExpectedCliRejection $_ @($Expected) })
        Assert-That ($Matching.Count -eq 1) "CLI $Name has no unique correlated rejection diagnostic."
        $Matching | ConvertTo-Json -Depth 12 | Set-Content -LiteralPath (Join-Path $ShouRun "$Name.diagnostics.json") -Encoding UTF8
        $ShouExpectedRejections.Add($Expected)
    }
    return $Json
}
function Select-Fixture([string]$Page, [string]$Path = $ShouPayload) {
    # Each folder journey starts on the real initial page. Result pages retain their
    # scan when revisited and intentionally hide the initial folder picker button.
    Close-App
    Start-App
    Navigate-Page $Page @('empty')
    Invoke-Control 'storage.choose'
    # Windows exposes the native folder input as either the Edit (1148) or its
    # ComboBox host (1152). Keep discovery restricted to this app process.
    $Field = Wait-Until {
        $Condition = [Windows.Automation.AndCondition]::new(
            [Windows.Automation.PropertyCondition]::new([Windows.Automation.AutomationElement]::ProcessIdProperty, $ShouProcess.Id),
            [Windows.Automation.OrCondition]::new(
                [Windows.Automation.PropertyCondition]::new([Windows.Automation.AutomationElement]::AutomationIdProperty, '1148'),
                [Windows.Automation.PropertyCondition]::new([Windows.Automation.AutomationElement]::AutomationIdProperty, '1152')))
        [Windows.Automation.AutomationElement]::RootElement.FindFirst([Windows.Automation.TreeScope]::Descendants, $Condition)
    } 'native folder picker'
    # Initial folder enumeration can replace the input after the dialog appears.
    # Read back the real input and retry the same generated path if it does.
    for ($Attempt = 0; $Attempt -lt 3; $Attempt++) {
        $ValuePattern = $null
        if ($Field.TryGetCurrentPattern([Windows.Automation.ValuePattern]::Pattern, [ref]$ValuePattern)) {
            $ValuePattern.SetValue($Path)
        } else {
            # Some system pickers expose their native Edit without managed UIA
            # patterns. Restrict the native message to the observed app-owned HWND.
            $Handle = [IntPtr]::new($Field.Current.NativeWindowHandle)
            $Owner = [uint32]0; $Result = [UIntPtr]::Zero
            [ShouPickerNative]::GetWindowThreadProcessId($Handle, [ref]$Owner) | Out-Null
            Assert-That ($Handle -ne [IntPtr]::Zero -and $Owner -eq $ShouProcess.Id -and $Field.Current.ClassName -eq 'Edit') 'Folder input is not a verified native Edit.'
            Assert-That ([ShouPickerNative]::SetText($Handle, 0x000C, [UIntPtr]::Zero, $Path, 2, 2000, [ref]$Result) -ne [IntPtr]::Zero -and $Result -ne [UIntPtr]::Zero) 'Native folder input rejected the generated path.'
        }
        Start-Sleep -Milliseconds 300
        if ($null -ne $ValuePattern) {
            $ActualInput = $ValuePattern.Current.Value
        } else {
            $Text = [Text.StringBuilder]::new(32768)
            Assert-That ([ShouPickerNative]::GetText($Handle, 0x000D, [UIntPtr]::new([uint64]$Text.Capacity), $Text, 2, 2000, [ref]$Result) -ne [IntPtr]::Zero) 'Native folder input read timed out.'
            $ActualInput = $Text.ToString()
        }
        if ($ActualInput -ne $Path) { continue }
        $Dialog = [Windows.Automation.TreeWalker]::ControlViewWalker.GetParent($Field)
        $Select = $null
        while ($null -ne $Dialog -and $Dialog.Current.ProcessId -eq $ShouProcess.Id) {
            $Select = $Dialog.FindFirst([Windows.Automation.TreeScope]::Descendants,
                [Windows.Automation.PropertyCondition]::new([Windows.Automation.AutomationElement]::AutomationIdProperty, '1'))
            if ($null -ne $Select) { break }
            $Dialog = [Windows.Automation.TreeWalker]::ControlViewWalker.GetParent($Dialog)
        }
        Assert-That ($null -ne $Select) 'Native folder picker Select button is unavailable.'
        $InvokePattern = $null
        if ($Select.TryGetCurrentPattern([Windows.Automation.InvokePattern]::Pattern, [ref]$InvokePattern)) {
            $InvokePattern.Invoke()
        } else {
            $Handle = [IntPtr]::new($Select.Current.NativeWindowHandle)
            $Owner = [uint32]0; $Result = [UIntPtr]::Zero
            [ShouPickerNative]::GetWindowThreadProcessId($Handle, [ref]$Owner) | Out-Null
            Assert-That ($Handle -ne [IntPtr]::Zero -and $Owner -eq $ShouProcess.Id -and $Select.Current.ClassName -eq 'Button') 'Folder selection is not a verified native Button.'
            Assert-That ([ShouPickerNative]::Click($Handle, 0x00F5, [UIntPtr]::Zero, [IntPtr]::Zero, 2, 2000, [ref]$Result) -ne [IntPtr]::Zero) 'Native folder selection timed out.'
        }
        $SelectionDeadline = [DateTime]::UtcNow.AddSeconds(3)
        do {
            if ((Find-Control 'storage.choose').Current.Name -eq $Path) { return }
            Start-Sleep -Milliseconds 150
        } while ([DateTime]::UtcNow -lt $SelectionDeadline)
    }
    $null = Wait-Until { (Find-Control 'storage.choose').Current.Name -eq $Path } 'selected fixture folder'
}
