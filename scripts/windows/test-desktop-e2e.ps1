    }
    Close-App
    Run-Step '02-generated-cli-scan-rules-and-plan' {
        $Workspace = (Run-Cli 'workspace-add' @('workspaces', 'add', '--path', $ShouPayload, '--root-ref', 'developer-workspaces')).data.id
