"""Validate shared design values and render native, build-time resources."""
import hashlib
import json
import math
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/design/tokens.json'
SWIFT_OUTPUT = ROOT / 'apps/macos/Sources/ShouDesign.generated.swift'
GROUPS = {'colors': 'Color', 'numbers': 'x:Double', 'radii': 'CornerRadius', 'thicknesses': 'Thickness'}


def validate(tokens):
    if not isinstance(tokens, dict) or set(tokens) != {'schema_version', *GROUPS}:
        raise ValueError('Design tokens must contain schema_version and the four supported groups')
    if type(tokens['schema_version']) is not int or tokens['schema_version'] != 1:
        raise ValueError('Unknown design token schema')
    seen = set()
    for group in GROUPS:
        if not isinstance(tokens[group], dict):
            raise ValueError(f'{group}: expected a token dictionary')
        for key, value in tokens[group].items():
            if not isinstance(key, str) or not re.fullmatch(r'Shou[A-Z][A-Za-z0-9]*', key) or key in seen:
                raise ValueError(f'Invalid or duplicate design token: {key}')
            seen.add(key)
            if group == 'colors':
                if not isinstance(value, str) or not re.fullmatch(r'#[0-9A-Fa-f]{8}', value):
                    raise ValueError(f'{key}: expected #AARRGGBB sRGB color')
            elif group == 'thicknesses' and isinstance(value, list):
                if len(value) != 4 or any(type(part) not in (int, float) or not 0 <= part <= 4096 or not math.isfinite(part) for part in value):
                    raise ValueError(f'{key}: expected four finite left/top/right/bottom values between 0 and 4096')
            elif type(value) not in (int, float) or not 0 <= value <= 4096 or not math.isfinite(value):
                raise ValueError(f'{key}: expected a finite number between 0 and 4096')
    return tokens


def load():
    def unique_pairs(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f'Duplicate design source key: {key}')
            result[key] = value
        return result
    tokens = validate(json.loads(SOURCE.read_text(encoding='utf-8'), object_pairs_hook=unique_pairs))
    reference = json.loads((ROOT / 'assets/design/radix-colors.json').read_text(encoding='utf-8'))
    if set(reference['tokens']) != set(tokens['colors']):
        raise ValueError('Every color token must have Radix scale provenance')
    for key, origin in reference['tokens'].items():
        value = reference['palettes'][origin['appearance']][origin['scale'] + str(origin['step'])][1:]
        expected = '#FF' + value if len(value) == 6 else '#' + value[6:] + value[:6]
        if tokens['colors'][key].upper() != expected.upper():
            raise ValueError(f'{key}: color differs from the declared Radix scale')
    return tokens


def xaml(tokens):
    validate(tokens)
    tree = ET.Element('ResourceDictionary', {
        'xmlns': 'http://schemas.microsoft.com/winfx/2006/xaml/presentation',
        'xmlns:x': 'http://schemas.microsoft.com/winfx/2006/xaml',
    })
    for group, element in GROUPS.items():
        for key, value in sorted(tokens[group].items()):
            ET.SubElement(tree, element, {'x:Key': key}).text = ','.join(str(part) for part in value) if isinstance(value, list) else str(value)
    ET.indent(tree, space='  ')
    return ET.tostring(tree, encoding='utf-8', xml_declaration=True) + b'\n'


def swift(tokens):
    validate(tokens)
    lines = [
        '// Generated by scripts/generate-windows-resources.py; do not edit.',
        '// Source: assets/design/tokens.json',
        '// Source SHA-256: ' + hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        'import SwiftUI', '', 'enum ShouDesign {',
    ]
    for group in GROUPS:
        for key, value in sorted(tokens[group].items()):
            name = key[4].lower() + key[5:]
            if group == 'colors':
                alpha, red, green, blue = [int(value[index:index + 2], 16) for index in (1, 3, 5, 7)]
                expression = f'Color(.sRGB, red: {red}.0 / 255, green: {green}.0 / 255, blue: {blue}.0 / 255, opacity: {alpha}.0 / 255)'
                lines.append(f'    static let `{name}` = {expression}')
            elif group == 'thicknesses' and isinstance(value, list):
                left, top, right, bottom = value
                lines.append(f'    static let `{name}` = EdgeInsets(top: {top}, leading: {left}, bottom: {bottom}, trailing: {right})')
            else:
                lines.append(f'    static let `{name}`: CGFloat = {value}')
    return ('\n'.join(lines + ['}', ''])).encode()
